//! Synthetic metadata substitutes only the provider boundary. Ownership,
//! persisted root policy, actual native payload hashing and package publication
//! use production code; no account or public download is used.
use super::*;
use crate::commands::commands_mod_staging::{
    ThunderstoreInstallIntent, inspect_thunderstore_startup, root_thunderstore_intents_with_policy,
    stage_thunderstore_online_mod_sources, stage_thunderstore_online_mod_sources_for_startup,
};

struct Fixture {
    root: PathBuf,
}
impl Fixture {
    fn new() -> Self {
        let root = std::env::temp_dir().join(format!(
            "langame-ts-policy-chain-{}",
            uuid::Uuid::new_v4().simple()
        ));
        fs::create_dir_all(root.join("CoreKeeperServer_Data/StreamingAssets/Mods")).unwrap();
        fs::write(root.join("CoreKeeperServer.exe"), b"MZfixture").unwrap();
        Self { root }
    }
    fn target(&self) -> ResolvedManualModTarget {
        ResolvedManualModTarget {
            instance_id: "fixture".into(),
            module_id: "corekeeper".into(),
            source_label: "Thunderstore".into(),
            target_label: "native Mods".into(),
            target_path: self.root.join("CoreKeeperServer_Data/StreamingAssets/Mods"),
            accepts: vec!["folder".into()],
            id_strategy: None,
        }
    }
    fn source(
        &self,
        version: &str,
        intent: ThunderstoreInstallIntent,
    ) -> DownloadedManualModSource {
        let path = self
            .root
            .join(format!("download-{}", uuid::Uuid::new_v4().simple()));
        fs::create_dir(&path).unwrap();
        fs::write(path.join("ModManifest.json"), br#"{"name":"fixture"}"#).unwrap();
        fs::write(path.join("Plugin.dll"), format!("MZ{version}")).unwrap();
        DownloadedManualModSource {
            path,
            label: "Author-Plugin".into(),
            identity: OnlineModIdentity {
                provider: "thunderstore".into(),
                project: "Author-Plugin".into(),
                historical_names: Vec::new(),
                version: version.into(),
                dependencies: Vec::new(),
                thunderstore_intent: Some(intent),
            },
        }
    }
}
impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn response(version: &str) -> ThunderstorePackageMetadata {
    serde_json::from_value(json!({"full_name":"Author-Plugin","community_listings":[{"community":"core-keeper"}],"latest":{"version_number":version,"download_url":format!("https://thunderstore.io/package/download/Author/Plugin/{version}/"),"dependencies":[]}})).unwrap()
}

#[tokio::test]
async fn ui_versionful_download_follow_latest_queries_new_version_on_next_start_but_pin_remains_fixed()
 {
    // This is the versionful canonical URL generated by the real UI's
    // Mod-Manager parser. Its explicit default policy must not become a pin.
    for policy in ["follow_latest", "pinned"] {
        let fixture = Fixture::new();
        let references = vec!["https://thunderstore.io/package/Author/Plugin/1.0.0/".into()];
        let intent=root_thunderstore_intents_with_policy(&references,Some(policy)).unwrap()["thunderstore-Author-Plugin"].clone();
        stage_thunderstore_online_mod_sources(
            fixture.target(),
            &[fixture.source("1.0.0", intent.clone())],
            None,
        )
        .unwrap();
        let proof = inspect_thunderstore_startup(&fixture.target()).unwrap();
        let mut requested = Vec::new();
        let selected = resolve_packages(
            thunderstore_game_profile("corekeeper").unwrap(),
            &proof.references,
            |request| {
                requested.push(request.version.clone());
                std::future::ready(Ok(response(request.version.as_deref().unwrap_or("2.0.0"))))
            },
        )
        .await
        .unwrap();
        assert_eq!(selected.len(), 1);
        if policy == "follow_latest" {
            assert_eq!(requested, [None]);
            assert_eq!(selected[0].latest.version_number, "2.0.0");
            assert!(package_needs_download(&proof.packages, &selected[0]));
            stage_thunderstore_online_mod_sources_for_startup(
                fixture.target(),
                &[fixture.source("2.0.0", intent)],
                &proof,
                &app_steamcmd::InstallCancellation::new(),
            )
            .unwrap();
            let after = inspect_thunderstore_startup(&fixture.target()).unwrap();
            assert_eq!(after.packages[0].version, "2.0.0");
            assert_eq!(
                after.references,
                ["https://thunderstore.io/package/Author/Plugin/"]
            );
        } else {
            assert_eq!(requested, [Some("1.0.0".into())]);
            assert!(!package_needs_download(&proof.packages, &selected[0]));
            assert_eq!(
                inspect_thunderstore_startup(&fixture.target())
                    .unwrap()
                    .packages[0]
                    .version,
                "1.0.0"
            );
        }
    }
}

#[tokio::test]
async fn warm_packages_still_query_metadata_and_only_skip_identical_selected_content() {
    let installed = vec![
        crate::commands::commands_mod_staging::CachedThunderstorePackage {
            project: "Author-Plugin".into(),
            version: "1.0.0".into(),
            dependencies: Vec::new(),
        },
    ];
    let mut calls = 0;
    let selected = resolve_packages(
        thunderstore_game_profile("corekeeper").unwrap(),
        &["https://thunderstore.io/package/Author/Plugin/".into()],
        |request| {
            calls += 1;
            assert!(request.version.is_none());
            std::future::ready(Ok(response("1.0.0")))
        },
    )
    .await
    .unwrap();
    assert_eq!(calls, 1);
    assert!(!package_needs_download(&installed, &selected[0]));
    let mut changed = response("1.0.0");
    changed.latest.dependencies = vec!["Author-Library-1.0.0".into()];
    assert!(package_needs_download(&installed, &changed));
}

#[tokio::test]
async fn provider_failure_is_safe_and_cancellation_never_becomes_cached_start() {
    let cancellation = app_steamcmd::InstallCancellation::new();
    let failure = provider_result(
        std::future::ready(Err::<(), String>(
            "https://secret.invalid/?token=hidden".into(),
        )),
        Some(&cancellation),
        app_core::RuntimeModUpdateReason::Request,
    )
    .await
    .err()
    .unwrap();
    assert_eq!(
        failure.reason(),
        Some(app_core::RuntimeModUpdateReason::Request)
    );
    assert!(!failure.message.contains("secret"));
    assert!(!failure.message.contains("token"));
    cancellation.cancel();
    let cancelled = provider_result(
        std::future::ready(Ok::<(), String>(())),
        Some(&cancellation),
        app_core::RuntimeModUpdateReason::Request,
    )
    .await
    .err()
    .unwrap();
    assert_eq!(cancelled.reason(), None);
    assert!(cancelled.is_cancelled());
    use crate::commands::commands_mods::mod_download::ModDownloadFailure;
    assert!(download_failure(ModDownloadFailure::Cancelled).is_cancelled());
    assert_eq!(
        download_failure(ModDownloadFailure::Network("network detail".into())).reason(),
        Some(app_core::RuntimeModUpdateReason::Network)
    );
    assert_eq!(
        download_failure(ModDownloadFailure::Http("private HTTP details".into())).reason(),
        Some(app_core::RuntimeModUpdateReason::Http)
    );
    let local = download_failure(ModDownloadFailure::Terminal(
        "permission denied or program fault".into(),
    ));
    assert_eq!(local.reason(), None);
    assert!(!local.message.contains("program fault"));
}
