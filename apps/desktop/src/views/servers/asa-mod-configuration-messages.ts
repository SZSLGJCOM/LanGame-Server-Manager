export function asaModConfigurationText(locale: string, key: CopyKey, params: Record<string, string | number> = {}): string {
  const text = (locale === "zh-CN" ? zh : en)[key];
  return text.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? ""));
}
