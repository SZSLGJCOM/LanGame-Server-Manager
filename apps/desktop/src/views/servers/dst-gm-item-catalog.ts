let itemSearchIndex: { option: DstGmItemOption; text: string }[] | undefined;

export function searchDstGmItemOptions(query: string, limit = 80): DstGmItemOption[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) {
    return DST_GM_ITEM_OPTIONS.slice(0, limit);
  }
  itemSearchIndex ??= DST_GM_ITEM_OPTIONS.map((option) => ({
    option,
    text: `${option.value} ${option.label} ${option.category} ${dstPrefabSearchAliases(option)}`.toLowerCase()
  }));
  const matches: DstGmItemOption[] = [];
  for (const item of itemSearchIndex) {
    if (item.text.includes(normalized)) {
      matches.push(item.option);
      if (matches.length >= limit) {
        break;
      }
    }
  }
  return matches;
}
